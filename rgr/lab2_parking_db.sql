-- DROP DATABASE IF EXISTS parking;

CREATE DATABASE parking
    WITH
    OWNER            = postgres
    ENCODING         = 'UTF8'
    LC_COLLATE       = 'Russian_Russia.1251'
    LC_CTYPE         = 'Russian_Russia.1251'
    TEMPLATE         = template0
    TABLESPACE       = pg_default
    CONNECTION LIMIT = -1
    IS_TEMPLATE      = False;

COMMENT ON DATABASE parking
    IS 'База данных автостоянки: договоры с клиентами, транспортные средства, электронная регистрация проездов по госномеру, оплата услуг';

-- Характеристики создаваемой базы данных:
--   владелец                  — суперпользователь postgres;
--   кодировка                 — UTF-8;
--   порядок сортировки строк  — локаль Russian_Russia.1251;
--   классификация символов    — локаль Russian_Russia.1251;
--   табличное пространство    — pg_default;
--   ограничение на количество одновременных подключений отсутствует;
--   база не является шаблоном (клонировать могут только суперпользователь
--   и владелец).
-- TEMPLATE = template0 указан потому, что задаваемая локаль может
-- отличаться от локали шаблонной базы template1.
